import csv
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

import psycopg
from confluent_kafka import Consumer
from dotenv import load_dotenv


load_dotenv()

TOPIC_NAME = "clima-eventos"
BOOTSTRAP_SERVERS = os.getenv("KAFKA_BOOTSTRAP_SERVERS", "localhost:9092")
GROUP_ID = "clima-consumer-group"
DATABASE_URL = os.getenv("DATABASE_URL")
RESULTS_DIR = Path(__file__).resolve().parents[1] / "results"
CSV_FIELDS = ["cidade", "temperatura", "umidade", "descricao", "timestamp"]

if not DATABASE_URL:
    raise RuntimeError(
        "DATABASE_URL não encontrada. Configure a URI PostgreSQL no arquivo .env."
    )

consumer = Consumer(
    {
        "bootstrap.servers": BOOTSTRAP_SERVERS,
        "group.id": GROUP_ID,
        "auto.offset.reset": "earliest",
        "enable.auto.commit": False,
    }
)
consumer.subscribe([TOPIC_NAME])


def preparar_tabela() -> None:
    """Cria a tabela de eventos se necessário e restringe o acesso pela Data API."""
    with psycopg.connect(DATABASE_URL, connect_timeout=10) as conexao:
        conexao.execute(
            """
            CREATE TABLE IF NOT EXISTS public.clima_eventos (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                cidade text NOT NULL,
                temperatura double precision NOT NULL,
                umidade integer NOT NULL,
                descricao text NOT NULL,
                coletado_em timestamptz NOT NULL,
                recebido_em timestamptz NOT NULL DEFAULT now()
            )
            """
        )
        conexao.execute(
            """
            CREATE INDEX IF NOT EXISTS clima_eventos_cidade_data_idx
            ON public.clima_eventos (cidade, coletado_em DESC)
            """
        )
        conexao.execute(
            "ALTER TABLE public.clima_eventos ENABLE ROW LEVEL SECURITY"
        )
        conexao.execute(
            "REVOKE ALL ON TABLE public.clima_eventos FROM anon, authenticated"
        )


def timestamp_utc(valor: object) -> datetime:
    return datetime.fromtimestamp(float(valor), tz=timezone.utc)


def salvar_evento(conexao: psycopg.Connection, evento: dict) -> None:
    """Persiste um evento no PostgreSQL sem duplicar uma reentrega do Kafka."""
    coletado_em = timestamp_utc(evento["timestamp"])
    cidade = str(evento["cidade"])

    conexao.execute(
        """
        INSERT INTO public.clima_eventos
            (cidade, temperatura, umidade, descricao, coletado_em)
        SELECT %s, %s, %s, %s, %s
        WHERE NOT EXISTS (
            SELECT 1
            FROM public.clima_eventos
            WHERE cidade = %s AND coletado_em = %s
        )
        """,
        (
            cidade,
            float(evento["temperatura"]),
            int(evento["umidade"]),
            str(evento["descricao"]),
            coletado_em,
            cidade,
            coletado_em,
        ),
    )
    conexao.commit()


def salvar_csv(evento: dict) -> Path:
    """Acrescenta o evento ao CSV do dia, usando a data de São Paulo."""
    horario_local = timestamp_utc(evento["timestamp"]).astimezone(
        ZoneInfo("America/Sao_Paulo")
    )
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    caminho = RESULTS_DIR / f"clima_eventos_{horario_local:%Y-%m-%d}.csv"
    precisa_cabecalho = not caminho.exists() or caminho.stat().st_size == 0

    with caminho.open("a", newline="", encoding="utf-8") as arquivo:
        writer = csv.DictWriter(arquivo, fieldnames=CSV_FIELDS)
        if precisa_cabecalho:
            writer.writeheader()
        writer.writerow({campo: evento[campo] for campo in CSV_FIELDS})

    return caminho


def main() -> None:
    print(f"Consumer iniciado. Escutando o tópico '{TOPIC_NAME}'...")
    preparar_tabela()

    try:
        with psycopg.connect(DATABASE_URL, connect_timeout=10) as conexao:
            while True:
                msg = consumer.poll(timeout=1.0)

                if msg is None:
                    continue

                if msg.error():
                    print(f"Erro no consumer: {msg.error()}")
                    continue

                try:
                    evento = json.loads(msg.value().decode("utf-8"))
                except (UnicodeDecodeError, json.JSONDecodeError) as erro:
                    print(f"Mensagem inválida ignorada: {type(erro).__name__}")
                    consumer.commit(message=msg, asynchronous=False)
                    continue

                salvar_evento(conexao, evento)
                caminho_csv = salvar_csv(evento)
                consumer.commit(message=msg, asynchronous=False)
                print(
                    f"Evento salvo no Supabase e exportado para {caminho_csv.name}"
                )

    except KeyboardInterrupt:
        print("\nEncerrando consumer...")

    finally:
        consumer.close()


if __name__ == "__main__":
    main()
