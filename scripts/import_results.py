import csv
import os
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Iterator
from zoneinfo import ZoneInfo

import psycopg


ROOT_DIR = Path(__file__).resolve().parents[1]
RESULTS_DIR = ROOT_DIR / "results"
DATABASE_URL = os.getenv("DATABASE_URL")
TIMEZONE = ZoneInfo("America/Sao_Paulo")
RETENTION_DAYS = 7


def data_limite(referencia: date | None = None) -> date:
    """Retorna a primeira data mantida na janela de sete dias, incluindo hoje."""
    hoje = referencia or datetime.now(TIMEZONE).date()
    return hoje - timedelta(days=RETENTION_DAYS - 1)


def data_do_arquivo(caminho: Path) -> date:
    try:
        return date.fromisoformat(caminho.stem.removeprefix("clima_eventos_"))
    except ValueError as erro:
        raise ValueError(f"Nome de arquivo inválido: {caminho.name}") from erro


def parse_timestamp(valor: str) -> datetime:
    """Converte timestamp Unix ou ISO 8601 em datetime UTC."""
    valor = valor.strip()
    if not valor:
        raise ValueError("timestamp vazio")

    try:
        return datetime.fromtimestamp(float(valor), tz=timezone.utc)
    except ValueError:
        pass

    try:
        instante = datetime.fromisoformat(valor.replace("Z", "+00:00"))
    except ValueError as erro:
        raise ValueError(f"timestamp inválido: {valor}") from erro

    if instante.tzinfo is None:
        instante = instante.replace(tzinfo=timezone.utc)
    return instante.astimezone(timezone.utc)


def parse_evento(linha: dict[str, str]) -> tuple[str, float, int, str, datetime]:
    """Valida e normaliza uma linha CSV para o esquema clima_eventos."""
    cidade = (linha.get("cidade") or "").strip()
    timestamp_texto = (
        linha.get("timestamp")
        or linha.get("coletado_em")
        or linha.get("horario")
        or ""
    )

    if not cidade:
        raise ValueError("cidade vazia")
    if not timestamp_texto.strip():
        raise ValueError("coluna timestamp, coletado_em ou horario ausente")

    try:
        temperatura = float(linha["temperatura"])
        umidade = int(float(linha["umidade"]))
    except (KeyError, TypeError, ValueError) as erro:
        raise ValueError("temperatura ou umidade inválida") from erro

    descricao = (linha.get("descricao") or "").strip()
    return (
        cidade,
        temperatura,
        umidade,
        descricao,
        parse_timestamp(timestamp_texto),
    )


def ler_eventos(caminho: Path) -> Iterator[tuple[str, float, int, str, datetime]]:
    with caminho.open("r", encoding="utf-8-sig", newline="") as arquivo:
        leitor = csv.DictReader(arquivo)
        campos = set(leitor.fieldnames or [])
        obrigatorios = {"cidade", "temperatura", "umidade"}
        if not obrigatorios.issubset(campos):
            raise ValueError(
                f"{caminho.name}: cabeçalho precisa conter "
                "cidade, temperatura e umidade"
            )

        if not ({"timestamp", "coletado_em", "horario"} & campos):
            raise ValueError(
                f"{caminho.name}: cabeçalho precisa conter timestamp, "
                "coletado_em ou horario"
            )

        for numero_linha, linha in enumerate(leitor, start=2):
            try:
                yield parse_evento(linha)
            except ValueError as erro:
                raise ValueError(
                    f"{caminho.name}, linha {numero_linha}: {erro}"
                ) from erro


def preparar_tabela(conexao: psycopg.Connection) -> None:
    conexao.execute(
        """
        CREATE TABLE IF NOT EXISTS public.clima_eventos (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cidade text NOT NULL,
            temperatura double precision NOT NULL,
            umidade integer NOT NULL,
            descricao text NOT NULL,
            coletado_em timestamptz NOT NULL,
            recebido_em timestamptz NOT NULL DEFAULT now()
        )
        """
    )
    conexao.execute(
        """
        CREATE INDEX IF NOT EXISTS clima_eventos_cidade_data_idx
        ON public.clima_eventos (cidade, coletado_em DESC)
        """
    )
    conexao.execute("ALTER TABLE public.clima_eventos ENABLE ROW LEVEL SECURITY")
    conexao.execute(
        "REVOKE ALL ON TABLE public.clima_eventos FROM anon, authenticated"
    )


def importar_arquivo(
    conexao: psycopg.Connection,
    caminho: Path,
    limite: date,
    hoje: date,
) -> tuple[int, int]:
    lidas = 0
    inseridas = 0

    for evento in ler_eventos(caminho):
        cidade, temperatura, umidade, descricao, coletado_em = evento
        data_evento = coletado_em.astimezone(TIMEZONE).date()
        lidas += 1
        if data_evento < limite or data_evento > hoje:
            continue

        resultado = conexao.execute(
            """
            INSERT INTO public.clima_eventos
                (cidade, temperatura, umidade, descricao, coletado_em)
            SELECT %s, %s, %s, %s, %s
            WHERE NOT EXISTS (
                SELECT 1 FROM public.clima_eventos
                WHERE cidade = %s AND coletado_em = %s
            )
            """,
            (
                cidade,
                temperatura,
                umidade,
                descricao,
                coletado_em,
                cidade,
                coletado_em,
            ),
        )
        inseridas += max(resultado.rowcount, 0)

    return lidas, inseridas


def main() -> None:
    if not DATABASE_URL:
        raise RuntimeError("Configure DATABASE_URL nos Secrets do GitHub Actions.")

    hoje = datetime.now(TIMEZONE).date()
    limite = data_limite(hoje)
    arquivos = sorted(RESULTS_DIR.glob("clima_eventos_*.csv"))
    arquivos_validos = [
        arquivo for arquivo in arquivos if limite <= data_do_arquivo(arquivo) <= hoje
    ]

    total_lidas = 0
    total_inseridas = 0
    with psycopg.connect(DATABASE_URL, connect_timeout=15) as conexao:
        preparar_tabela(conexao)
        for caminho in arquivos_validos:
            lidas, inseridas = importar_arquivo(conexao, caminho, limite, hoje)
            total_lidas += lidas
            total_inseridas += inseridas
            print(f"{caminho.name}: {lidas} linhas lidas, {inseridas} novas.")

        # Apaga somente depois de importar com sucesso todos os arquivos válidos.
        conexao.execute(
            """
            DELETE FROM public.clima_eventos
            WHERE coletado_em < %s OR coletado_em >= %s
            """,
            (
                datetime.combine(limite, datetime.min.time(), tzinfo=TIMEZONE),
                datetime.combine(hoje + timedelta(days=1), datetime.min.time(), tzinfo=TIMEZONE),
            ),
        )

    for caminho in arquivos:
        if caminho not in arquivos_validos:
            caminho.unlink()
            print(f"Arquivo removido por estar fora da janela: {caminho.name}")

    print(
        f"Janela mantida: {limite.isoformat()} até {hoje.isoformat()} "
        f"(7 dias corridos). {total_lidas} linhas lidas, "
        f"{total_inseridas} registros novos."
    )


if __name__ == "__main__":
    main()
